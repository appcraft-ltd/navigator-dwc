const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { runtimeVersion } = require('./runtime.cjs');
const { assertNativeBaseline } = require('./native-baseline.cjs');
const root = path.resolve(__dirname, '../..');
const [destination, receiptPath] = process.argv.slice(2);
if (!destination || !receiptPath) throw new Error('Usage: export-ota.cjs NEW_EXPORT_DIR TARGET_APK_RECEIPT');
const receipt = JSON.parse(fs.readFileSync(receiptPath));
const expectedRuntime = receipt.runtimeVersion;
if (runtimeVersion() !== expectedRuntime) throw new Error('Native changes require an APK.');
assertNativeBaseline(root, receipt.sourceSha);
if (execFileSync('git', ['status', '--porcelain'], { cwd: root }).length) throw new Error('Commit reviewed source before exporting an OTA.');
if (fs.existsSync(destination)) throw new Error('Export directory must be new.');
const sha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
execFileSync(process.execPath, [require.resolve('expo/bin/cli'), 'export', '--platform', 'android', '--output-dir', destination], { cwd: root, stdio: 'inherit' });
if (runtimeVersion() !== expectedRuntime || execFileSync('git', ['status', '--porcelain'], { cwd: root }).length) throw new Error('Source changed during export.');
assertNativeBaseline(root, receipt.sourceSha);
fs.writeFileSync(path.join(destination, 'export-runtime.json'), JSON.stringify({ runtimeVersion: expectedRuntime, sourceSha: sha, nativeBaselineSha: receipt.sourceSha }) + '\n');
